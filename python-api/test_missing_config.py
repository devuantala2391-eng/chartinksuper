import requests
import json
import time
from pathlib import Path

def test_missing_config():
    """Test that system handles missing precalculatedIndicators.json properly."""
    
    base_url = "http://localhost:8001"
    test_query = "daily_close > 100 and daily_rsi_14 > 30"
    
    print("=" * 60)
    print("TESTING WITH MISSING precalculatedIndicators.json")
    print("=" * 60)
    
    # Verify file doesn't exist
    precalc_file = Path("precalculatedIndicators.json")
    if precalc_file.exists():
        print("[WARNING] precalculatedIndicators.json exists (should be deleted)")
    else:
        print("[OK] precalculatedIndicators.json does not exist")
    
    print(f"\nQuery: {test_query}")
    print("-" * 60)
    
    print("Making API request...")
    start_time = time.time()
    
    try:
        response = requests.post(
            f"{base_url}/api/query/latest",
            json={"query": test_query},
            timeout=120
        )
        
        elapsed = time.time() - start_time
        print(f"Response received in {elapsed:.2f} seconds")
        print(f"Status code: {response.status_code}")
        
        if response.status_code == 200:
            result = response.json()
            matches = len(result.get('result', []))
            print(f"[SUCCESS] Query executed! Found {matches} matches")
            
            # Check if config file was created
            if precalc_file.exists():
                print("\n[SUCCESS] precalculatedIndicators.json was created!")
                
                with open(precalc_file, 'r') as f:
                    data = json.load(f)
                    indicators = data.get('indicators', [])
                    status = data.get('status', 'unknown')
                    auto_generated = data.get('autoGenerated', False)
                    
                    print(f"  Status: {status}")
                    print(f"  Auto-generated: {auto_generated}")
                    print(f"  Indicators count: {len(indicators)}")
                    
                    # Check for daily_rsi_14
                    has_rsi_14 = any(
                        ind.get('timeframe') == 'daily' and
                        ind.get('name') == 'rsi' and
                        ind.get('params', {}).get('period') == 14
                        for ind in indicators
                    )
                    
                    if has_rsi_14:
                        print("  [OK] daily_rsi_14 is in the configuration")
                    else:
                        print("  [WARNING] daily_rsi_14 not found in configuration")
            else:
                print("\n[ERROR] precalculatedIndicators.json was NOT created")
            
            # Check a sample data file
            sample_file = Path("precalculatedStorage/3PLAND_piped.json")
            if sample_file.exists():
                with open(sample_file, 'r') as f:
                    stock_data = json.load(f)
                    if stock_data.get("data"):
                        last_candle = stock_data["data"][-1]
                        has_rsi = "daily_rsi_14" in last_candle
                        print(f"\nData file has daily_rsi_14: {has_rsi}")
                        if has_rsi:
                            value = last_candle.get("daily_rsi_14")
                            print(f"Value: {value}")
        else:
            print(f"[ERROR] Status {response.status_code}")
            print(f"Response: {response.text}")
            
    except requests.exceptions.Timeout:
        print("[ERROR] Request timed out")
    except Exception as e:
        print(f"[ERROR] {e}")

if __name__ == "__main__":
    test_missing_config()